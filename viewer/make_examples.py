"""Write viewer/examples.js: the spec's example records, collections and table spec, which the
viewer opens with. Run after changing schema/examples/:  python viewer/make_examples.py
(tests/test_viewer.py checks that examples.js is current)."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EXAMPLES = ROOT / "schema" / "examples"
FILES = [
    "paper.estimation-collection.json",
    "session.estimation-collection.json",
    "replication.estimation-collection.json",
    "replication.members.jsonl",
    "iv.estimation.json",
    "glm-logit.estimation.json",
    "dfeols-linear-fe.estimation.json",
    "paper.estimation-table.json",
]


def content() -> str:
    files = [{"name": n, "text": (EXAMPLES / n).read_text(encoding="utf-8")} for n in FILES]
    body = json.dumps(files, ensure_ascii=False, indent=0)
    return (
        "// Generated by viewer/make_examples.py from schema/examples/ (CC0). Don't edit.\n"
        f"window.EST_EXAMPLES = {body};\n"
    )


if __name__ == "__main__":
    (ROOT / "viewer" / "examples.js").write_text(content(), encoding="utf-8")
